/* Shadow & Shine Daily moved to the E&Languages member app (https://e-languages.vercel.app/shadow-daily).
   This worker removes its caches and unregisters itself so the old offline app shell is not served any more. */
self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (e) => {
  e.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k.startsWith("ssd-")).map((k) => caches.delete(k)));
    await self.registration.unregister();
    const clients = await self.clients.matchAll({ type: "window" });
    clients.forEach((c) => c.navigate(c.url));
  })());
});
